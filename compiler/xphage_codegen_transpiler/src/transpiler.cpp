inline std::string str_slice(const std::string& s, long long start, long long end) {
    long long len = (long long)s.size();
    if (start < 0) start += len;
    if (end < 0) end += len;
    start = start < 0 ? 0 : (start > len ? len : start);
    end   = end   < 0 ? 0 : (end   > len ? len : end);
    if (end <= start) return "";
    return s.substr((size_t)start, (size_t)(end - start));
}
