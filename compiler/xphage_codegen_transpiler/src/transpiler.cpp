TranspilerResult transpile_ir(const xphage::ir::IRModule& mod,
                               const std::string& output_cpp,
                               const TranspilerConfig& cfg) {
    TranspilerResult res;
    try {
        std::ofstream out(output_cpp);
        if (!out.is_open()) { res.error = "Cannot write: " + output_cpp; return res; }

        std::ostringstream s;
        s << boilerplate_header();
        s << "// XIL Module: " << mod.name << "\n";
        s << "#include <iostream>\n#include <string>\n#include <vector>\n"
             "#include <unordered_map>\n#include <functional>\n#include <sstream>\n"
             "#include <thread>\n#include <chrono>\n#include <cstdlib>\n#include <future>\n"
             "#include <cmath>\n#include <memory>\n#include <mutex>\n#include <optional>\n"
             "#include <stdexcept>\n#include <type_traits>\n#include <variant>\n#include <tuple>\n\n";
        // Stdlib-module-specific includes, matching exactly what the
        // AST transpiler path includes for the same ~link (see its
        // own header-emission block near the top of this file) — see
        // xil_stdlib_runtime's own comment for why these two things
        // (headers here, implementations further below) need to
        // travel together.
        {
            std::unordered_set<std::string> imports(mod.imports.begin(), mod.imports.end());
            if (imports.count("math")) {
                s << "#include <numeric>\n#include <random>\n#include <algorithm>\n";
            }
            if (imports.count("string")) {
                s << "#include <algorithm>\n#include <cctype>\n#include <regex>\n#include <iomanip>\n";
            }
            if (imports.count("io")) {
                s << "#include <filesystem>\n#include <fstream>\n#include <cstdio>\n";
            }
            if (imports.count("collections")) {
                s << "#include <algorithm>\n#include <vector>\n";
            }
            if (imports.count("math") || imports.count("string") ||
                imports.count("io")   || imports.count("collections")) {
                s << "\n";
            }
        }
        // NOTE: deliberately NOT `#include "xphage/runtime.hpp"` here.
        // That header lives under the project's include/ directory,
        // and nothing in the driver passes an -I flag pointing at it
        // when invoking the system C++ compiler on generated output
        // (the same latent gap exists on the AST transpiler path —
        // it just never surfaces there because that emitter inlines
        // its own Flux<T>/EventBus definitions directly into the
        // generated .cpp instead of depending on an external header).
        // Do the same here so XIL output is self-contained and does
        // not depend on being compiled from a specific working
        // directory or with a specific -I search path.
        s << xil_runtime_prelude();
        s << xil_stdlib_runtime(mod);

        // Imports (informational — headers for stdlib modules are
        // already included above unconditionally since the XIL
        // runtime prelude is small and self-contained).
        for (auto& imp : mod.imports) s << "// import: " << imp << "\n";
        if (!mod.imports.empty()) s << "\n";

        // Struct/type declarations first, so functions below can
        // reference them.
        for (auto& td : mod.types) s << emit_struct_decl(td);
        for (auto& ed : mod.enums) s << emit_enum_decl(ed);

        // Forward-declare every non-signature-only function before
        // any bodies are emitted, so call order in the source doesn't
        // matter (mirrors the "declaration order independence"
        // golden-test guarantee the AST path already provides).
        for (auto& fn : mod.functions) {
            if (fn.is_signature_only) continue; // no declaration at all —
                                                  // implementation is runtime-injected
            if (fn.blocks.empty() && !fn.is_extern) continue; // nothing to forward-declare
            if (fn.name == "main") continue; // the real entry point never needs a
                                              // forward declaration, and forcing its
                                              // return type to int here too would just
                                              // duplicate the logic already in emit()
            if (fn.is_extern) {
                // `str` has no defined C ABI (implementation-defined
                // std::string layout varies between standard library
                // vendors/versions) — the C-ABI-correct mapping is
                // `const char*`, matching how the AST transpiler's
                // emit_extern() already does this. Call sites append
                // .c_str() to string arguments and wrap a str-typed
                // return back into std::string (see the Call emission
                // fix below) so extern calls still feel like ordinary
                // X-Phage string values everywhere else in the
                // program.
                std::string ret = fn.ret_type == IRType::String
                                 ? "const char*"
                                 : xil_cpp_type(fn.ret_type, fn.ret_type_name);
                if (ret.empty()) ret = "void";
                // Deliberately NOT xil_cpp_name(fn.name) here: an
                // extern symbol's name must match the external
                // library's exported symbol exactly (no "::"
                // mangling, no C++-keyword rewriting) — this mirrors
                // emit_extern()'s identical reasoning on the AST
                // path. Renaming it would silently break the link
                // against the real C/Rust symbol.
                s << "extern \"" << fn.extern_abi << "\" " << ret << " " << fn.name << "(";
                bool first = true;
                for (auto& p : fn.params) {
                    if (!first) s << ", ";
                    std::string pt = p.type == IRType::String
                                    ? "const char*"
                                    : xil_cpp_type(p.type, p.type_name);
                    if (pt.empty()) pt = "auto&&";
                    s << pt;
                    first = false;
                }
                s << ");\n";
                continue;
            }
            std::string ret = xil_cpp_type(fn.ret_type, fn.ret_type_name);
            if (ret.empty()) ret = "void";
            s << ret << " " << xil_cpp_name(fn.name) << "(";
            bool first = true;
            for (auto& p : fn.params) {
                if (!first) s << ", ";
                std::string pt = xil_cpp_type(p.type, p.type_name);
                if (pt.empty()) pt = "auto&&";
                s << pt << " " << xil_cpp_name(p.name);
                first = false;
            }
            s << ");\n";
        }
        s << "\n";

        // Globals (after struct decls, since a global's type may be
        // a struct type; before function bodies, since bodies may
        // reference globals).
        for (auto& g : mod.globals) s << emit_global_decl(g);
        if (!mod.globals.empty()) s << "\n";

        // Build shared registries once for the whole module.
        StructRegistry sreg   = build_struct_registry(mod);
        GlobalRegistry greg   = build_global_registry(mod);
        FunctionRegistry freg = build_function_registry(mod);
        EnumRegistry ereg     = build_enum_registry(mod);

        // Function bodies. Signature-only stdlib declarations are
        // skipped entirely (no declaration, no body) — their
        // implementation is supplied by the runtime/prelude, and
        // emitting even a declaration for them risks exactly the
        // abs()/<cstdlib> collision documented in the log.
        for (auto& fn : mod.functions) {
            if (fn.is_signature_only) continue;
            if (fn.is_extern) continue; // declared above; body lives externally
            if (fn.blocks.empty()) continue;
            XILFunctionEmitter fe(fn, sreg, greg, freg, ereg);
            s << fe.emit();
        }

        out << s.str();
        out.close();

        std::string code = s.str();
        res.lines_emitted = std::count(code.begin(), code.end(), '\n');
        res.success     = true;
        res.output_path = output_cpp;
        if (cfg.verbose)
            std::cout << "[transpile_ir] Emitted " << res.lines_emitted
                      << " lines -> " << output_cpp << "\n";
    } catch (const std::exception& e) {
        res.error = std::string("XIL transpiler exception: ") + e.what();
    }
    return res;
}

