inline std::string str_split(const std::string& s, const std::string& delim) {
    if (delim.empty()) return s;
    std::string out; size_t pos = 0, prev = 0;
    while ((pos = s.find(delim, prev)) != std::string::npos) {
        if (!out.empty()) out += "\n";
        out += s.substr(prev, pos - prev);
        prev = pos + delim.size();
    }
    if (!out.empty()) out += "\n";
    out += s.substr(prev);
    return out;
}
