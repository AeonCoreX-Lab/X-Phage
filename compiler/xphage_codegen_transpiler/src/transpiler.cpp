inline std::string str_center(const std::string& s, long long width, const std::string& ch) {
    std::string fill = ch.empty() ? " " : ch;
    long long total = width - (long long)s.size();
    if (total <= 0) return s;
    long long left = total / 2, right = total - left;
    std::string out;
    for (long long i = 0; i < left; i++) out += fill.substr(0,1);
    out += s;
    for (long long i = 0; i < right; i++) out += fill.substr(0,1);
    return out;
}

