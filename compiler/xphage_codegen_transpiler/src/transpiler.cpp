TranspilerResult transpile_ast(const Program& ast,
                                const std::string& output_cpp,
                                const TranspilerConfig& cfg) {
    TranspilerResult res;
    try {
        ASTTranspiler t(cfg);
        std::string code = t.emit(ast);

        std::ofstream out(output_cpp);
        if (!out.is_open()) {
            res.error = "Cannot write: " + output_cpp;
            return res;
        }
        out << code;
        out.close();

        // Count lines
        res.lines_emitted = std::count(code.begin(), code.end(), '\n');
        res.output_path = output_cpp;
        res.success     = true;
        if (cfg.verbose)
            std::cout << "[transpiler] Emitted " << res.lines_emitted
                      << " lines → " << output_cpp << "\n";
    } catch (const std::exception& e) {
        res.error = std::string("Transpiler exception: ") + e.what();
    }
    return res;
}

