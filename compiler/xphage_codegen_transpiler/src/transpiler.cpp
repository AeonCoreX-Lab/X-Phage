    // Mirrors SectionDetector::is_pure_literal (xphage_interface) —
    // duplicated locally rather than taking a dependency on that
    // module from here. Used to decide whether a top-level AtomDecl
    // was emitted as a global constant (and must be excluded from
    // the implicit-main body loops below) or is a non-constant
    // top-level initializer that still belongs in main().
    static bool is_pure_literal(const ASTNodePtr& expr) {
        if (!expr) return true;
        switch (expr->kind) {
            case NodeKind::IntLit: case NodeKind::FloatLit:
            case NodeKind::BoolLit: case NodeKind::StringLit:
            case NodeKind::NullLit:
                return true;
            case NodeKind::UnaryOp:
                return !expr->children.empty() && is_pure_literal(expr->children[0]);
            default:
                return false;
        }
    }

    static bool is_top_level_const_atom(const ASTNodePtr& n) {
        if (!n || n->kind != NodeKind::AtomDecl) return false;
        return n->children.empty() || is_pure_literal(n->children[0]);
    }

    // A top-level Block is an "extern wrapper" if it was produced by
    // `extern "ABI" { pulse ... pulse ... }` — i.e. every child (if
    // any) is an ExternDecl. An empty block doesn't count (it isn't
    // produced by this grammar, but treat conservatively as "not").
    static bool is_extern_block(const ASTNode& n) {
        if (n.children.empty()) return false;
        for (auto& c : n.children) {
            if (!c || c->kind != NodeKind::ExternDecl) return false;
        }
        return true;
    }

