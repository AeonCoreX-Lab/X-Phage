// Small self-contained runtime prelude for the handful of stdlib-ish
// intrinsics XIL-generated code can call (fstring formatting, for-in
// iteration probing). Kept minimal and dependency-free rather than
// pulling in the full ASTTranspiler runtime surface, since the XIL
// backend is meant to be independently testable.
std::string xil_runtime_prelude() {
    return
        "// ── XIL runtime prelude ─────────────────────────────────\n"
        "template<typename T>\n"
        "class Flux {\n"
        "public:\n"
        "  T value;\n"
        "  std::vector<std::function<void(const T&)>> observers;\n"
        "  Flux() = default;\n"
        "  explicit Flux(T v) : value(std::move(v)) {}\n"
        "  Flux& operator=(T v) { value = std::move(v); notify(); return *this; }\n"
        "  operator const T&() const { return value; }\n"
        "  void subscribe(std::function<void(const T&)> cb) { observers.push_back(cb); }\n"
        "  void notify() { for(auto& cb: observers) cb(value); }\n"
        "  bool operator==(const T& o) const { return value == o; }\n"
        "  bool operator!=(const T& o) const { return value != o; }\n"
        "  friend bool operator==(const T& o,const Flux& f){return f.value==o;}\n"
        "  friend std::ostream& operator<<(std::ostream& os,const Flux& f){return os<<f.value;}\n"
        "};\n\n"
        "class EventBus {\n"
        "public:\n"
        "  using Handler = std::function<void(const std::unordered_map<std::string,std::string>&)>;\n"
        "  static EventBus& global() { static EventBus eb; return eb; }\n"
        "  void emit(const std::string& e, std::unordered_map<std::string,std::string> d={})\n"
        "    { auto it=handlers.find(e); if(it!=handlers.end()) for(auto& h:it->second) h(d); }\n"
        "  void on(const std::string& e, Handler h) { handlers[e].push_back(h); }\n"
        "private:\n"
        "  std::unordered_map<std::string,std::vector<Handler>> handlers;\n"
        "};\n\n"
        "template <typename T>\n"
        "std::string xp_to_string(const T& v) {\n"
        "    std::ostringstream oss; oss << v; return oss.str();\n"
        "}\n"
        "inline std::string xp_to_string(const std::string& v) { return v; }\n"
        "inline std::string xp_to_string(bool v) { return v ? \"true\" : \"false\"; }\n"
        "inline std::string xp_fstring_format(const std::string& raw) {\n"
        "    // Minimal passthrough: full {expr} interpolation happens in\n"
        "    // the AST transpiler path today. XIL forwards the raw text\n"
        "    // rather than silently dropping it, so output is at least\n"
        "    // inspectable/debuggable end-to-end.\n"
        "    return raw;\n"
        "}\n"
        "template <typename It, typename End>\n"
        "inline bool xp_iter_has_next(const It& cur, const End& end) {\n"
        "    return !(cur == end);\n"
        "}\n"
        "inline bool xp_iter_has_next(long long cur, long long end) { return cur < end; }\n"
        "\n";
}

